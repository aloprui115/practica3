    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
        String strNumero = txtNumero.getText().trim();
        String nombre = txtNombre.getText().trim();
        String strPuntos = txtPuntos.getText().trim();
        String strFecha = txtFecha.getText().trim();
        if (nombre.isEmpty() || !Validaciones.comprobarNumero(strNumero)) {
        lblError.setText("ERROR: Revisa el número y el nombre.");
        return;
        }
        if (!Validaciones.comprobarPuntos(strPuntos)) {
        lblError.setText("ERROR: Los puntos deben estar entre 0 y 1000.");
        return;
        }
        if (!Validaciones.comprobarFecha(strFecha)) {
        lblError.setText("ERROR: Fecha inválida. Usa dd/mm/aaaa (1900-2015).");
        return;
        }
        int numero = Integer.parseInt(strNumero);
        float puntos = Float.parseFloat(strPuntos);
        LocalDate fecha = Validaciones.convertirFecha(strFecha);
        controlador.anadirCliente(new Cliente(numero, nombre, puntos, fecha));
        // Limpiamos todo tras guardar
        lblError.setText("");
        txtNumero.setText("");
        txtNombre.setText("");
        txtPuntos.setText("");
        txtFecha.setText("");
    }//GEN-LAST:event_btnGuardarActionPerformed

